use crate::{equation_to_typst, text_export::{bare_content, indented, paragraph_with_defaults, Defaults}};
use model::{Block, Document, Paragraph};
use format::{DocumentFormat, FormatCapabilities, FormatResult, ReadSeek, WriteSeek};
use std::io::SeekFrom;

#[derive(Default)]
pub struct TypstFormat;

impl DocumentFormat for TypstFormat {
    fn id(&self) -> &'static str { "typst" }
    fn display_name(&self) -> &'static str { "Typst" }
    fn extensions(&self) -> &'static [&'static str] { &["typ"] }
    fn capabilities(&self) -> FormatCapabilities {
        FormatCapabilities { import: true, export: true, preserves_unknown_data: false, native_equations: true }
    }

    fn import(&self, input: &mut dyn ReadSeek) -> FormatResult<Document> {
        input.seek(SeekFrom::Start(0))?;
        let mut source = String::new();
        input.read_to_string(&mut source)?;
        Ok(import_structured_subset(&source))
    }

    fn export_warnings(&self, _document: &Document) -> Vec<String> {
        vec!["Typst export is a generated prose subset, not a lossless document save. Titles/headings and supported inherited text formatting are exported. Images, reference/review metadata, exact pagination and some structures are not preserved. Save a native .impress copy first.".into()]
    }

    fn export(&self, document: &Document, output: &mut dyn WriteSeek) -> FormatResult<()> {
        output.seek(SeekFrom::Start(0))?;
        output.write_all(export_structured(document).as_bytes())?;
        Ok(())
    }
}

/// The document as readable Typst: its defaults set once at the top, then one
/// block per paragraph, separated by blank lines.
pub fn export_structured(document: &Document) -> String {
    let defaults = Defaults::for_document(document);
    let mut parts = vec![format!("// Generated by Impress.\n\n{}", defaults.preamble())];
    for (section_index, section) in document.sections.iter().enumerate() {
        if section_index > 0 { parts.push("#pagebreak()".into()); }
        for block in &section.blocks {
            parts.push(block_to_typst(block, document, &defaults));
        }
    }
    parts.join("\n\n") + "\n"
}

fn block_to_typst(block: &Block, document: &Document, defaults: &Defaults) -> String {
    match block {
        Block::Paragraph(p) => paragraph_with_defaults(p, &document.styles, defaults),
        Block::Equation(eq) => equation_to_typst(eq),
        Block::Table(table) => {
            // What the cells share is set once around the table; each row is
            // then one line when its cells are short.
            let mut cell_paragraphs = Vec::new();
            for cell in table.rows.iter().flat_map(|r| &r.cells) {
                for block in &cell.blocks { if let Block::Paragraph(p) = block { cell_paragraphs.push(p); } }
            }
            let inner = Defaults::for_paragraphs(&cell_paragraphs, &document.styles);
            let columns = table.rows.first().map(|r| r.cells.len()).unwrap_or(1).max(1);
            let mut lines = vec![format!("columns: {columns},")];
            for row in &table.rows {
                let cells: Vec<String> = row.cells.iter().map(|cell| {
                    let parts: Vec<String> = cell.blocks.iter().filter(|b| matches!(b, Block::Paragraph(_)))
                        .map(|b| block_to_typst(b, document, &inner)).collect();
                    match parts.as_slice() {
                        [] => "[]".to_string(),
                        [only] => match bare_content(only) { Some(text) => format!("[{text}]"), None => format!("[\n{}\n]", indented(only)) },
                        many => format!("[\n{}\n]", indented(&many.join("\n"))),
                    }
                }).collect();
                let one_line = cells.join(", ");
                if !one_line.contains('\n') && one_line.len() <= 100 { lines.push(format!("{one_line},")); }
                else { lines.extend(cells.into_iter().map(|c| format!("{c},"))); }
            }
            let table = format!("#table(\n{}\n)", indented(&lines.join("\n")));
            let rules = inner.rules_within(defaults);
            if rules.is_empty() { table } else { format!("#[\n{}\n]", indented(&format!("{}\n{table}", rules.join("\n")))) }
        }
        Block::Image(image) => format!("// Picture {}: {:.1} × {:.1} mm (kept in the Impress document)", image.resource, image.width_mm, image.height_mm),
        Block::PageBreak { .. } => "#pagebreak()".into(),
        Block::ColumnBreak { .. } => "#colbreak()".into(),
        Block::Foreign(_) => "// Content Impress keeps but cannot show here (preserved in the Impress document)".into(),
    }
}

/// Literal-source importer. This is not a rich semantic round-trip parser.
/// No Typst code is interpreted or executed by this import path.
fn import_structured_subset(source: &str) -> Document {
    let mut document = Document::default();
    let section = document.sections.first_mut().expect("default section");
    let mut paragraph = String::new();
    for raw in source.lines() {
        let line = raw.trim_end();
        if line.starts_with("//") { continue; }
        if line.trim().is_empty() {
            if !paragraph.trim().is_empty() {
                section.blocks.push(Block::Paragraph(Paragraph::plain(paragraph.trim().to_owned())));
                paragraph.clear();
            }
            continue;
        }
        if !paragraph.is_empty() { paragraph.push(' '); }
        paragraph.push_str(line);
    }
    if !paragraph.trim().is_empty() { section.blocks.push(Block::Paragraph(Paragraph::plain(paragraph.trim().to_owned()))); }
    document.compatibility.push(model::CompatibilityIssue {
        code: "typst-source-import".into(), part: "source".into(),
        message: "Typst is opened as literal source paragraphs. Arbitrary Typst markup/scripts are not interpreted by this importer; no source code is executed. Use the native .impress document to retain editable document structure.".into(),
    });
    document
}
