#!/usr/bin/env python3
"""Writes crates/gui/src/ribbon/symbol_table.rs: the characters Insert > Symbol
offers, by category, with their Unicode names (from Python's unicodedata, so
Impress needs no name database of its own). Run from the source root."""
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'crates/gui/src/ribbon/symbol_table.rs'

def span(first, last):
    return [chr(c) for c in range(first, last + 1)]

COMMON = list('©®™°±×÷€£¥¢§¶•…—–«»“”‘’„‹›≤≥≠≈∞√∑∏∫∂∆πµΩαβγδθλσφω½¼¾¹²³→←↑↓↔⇒⇔✓✗★☆♥♦♣♠♪☐☑☒¬¦†‡‰′″')
CATEGORIES = [
    ('Common', COMMON),
    ('Latin', span(0x00C0, 0x00FF) + span(0x0100, 0x017F)),
    ('Greek', span(0x0391, 0x03A9) + span(0x03B1, 0x03C9) + list('ϑϕϖϰϱϵϐϒ')),
    ('Math', list('±×÷¬·') + span(0x2200, 0x22FF) + span(0x2070, 0x209C) + list('¹²³')),
    ('Arrows', span(0x2190, 0x21FF)),
    ('Currency', list('$¢£¤¥') + span(0x20A0, 0x20C0)),
    ('Punctuation', list('¡¿«»§¶') + span(0x2010, 0x2027) + span(0x2030, 0x205E)),
    ('Shapes', span(0x25A0, 0x25FF) + list('★☆✓✔✗✘')),
]
SKIP = {'Cc', 'Cf', 'Cn', 'Co', 'Cs', 'Zs', 'Zl', 'Zp', 'Mn', 'Me'}

def name(ch):
    words = unicodedata.name(ch).lower()
    return words[:1].upper() + words[1:]

def rust(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

lines = ['//! Generated by tools/build_symbol_table.py: the characters Insert > Symbol',
         '//! offers, by category, with their Unicode names. Do not edit by hand.',
         '',
         'pub(super) struct Category { pub name: &\'static str, pub symbols: &\'static [(char, &\'static str)] }',
         '',
         'pub(super) const CATEGORIES: &[Category] = &[']
total = 0
for title, chars in CATEGORIES:
    seen = []
    for ch in chars:
        if ch in seen or unicodedata.category(ch) in SKIP: continue
        try: unicodedata.name(ch)
        except ValueError: continue
        seen.append(ch)
    total += len(seen)
    lines.append(f'    Category {{ name: {rust(title)}, symbols: &[')
    for ch in seen:
        lines.append(f"        ('\\u{{{ord(ch):04X}}}', {rust(name(ch))}),")
    lines.append('    ] },')
lines.append('];')
OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Wrote {total} symbols in {len(CATEGORIES)} categories to {OUT.relative_to(ROOT)}')
