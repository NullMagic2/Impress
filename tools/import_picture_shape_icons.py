#!/usr/bin/env python3
"""Import LibreOffice Yaru crop-picker icons and embed their normalized PNGs.

Usage: python3 tools/import_picture_shape_icons.py [images_yaru_svg.zip]
Pass the archive to refresh SVG sources. With no argument, existing vendored
SVGs are rasterized without requiring a LibreOffice installation.
"""
from pathlib import Path
import json
import subprocess
import sys

from import_yaru_icons import YaruArchive

ROOT = Path(__file__).resolve().parents[1]
MAPPING = ROOT / 'design/picture-shape-icons.json'
SVG_DIRECTORY = ROOT / 'design/icons/picture-crops'
PNG_DIRECTORY = ROOT / 'crates/gui/assets/picture-crops'
EMBEDDED = ROOT / 'crates/gui/src/ribbon/picture_shape_icons.rs'
RASTERIZER = ROOT / 'tools/render_mock_icons/Cargo.toml'
# Same 64px raster and ink fit as the established toolbar artwork.
RASTER_INSET_PX = 1
INK_SIZE_PX = 54


def import_sources(mapping, archive_path):
    archive = YaruArchive(archive_path)
    for preset, source in mapping.items():
        svg = archive.svg(source['command'])
        (SVG_DIRECTORY / f'{preset}.svg').write_text(svg)


def rasterize():
    subprocess.run([
        'cargo', 'run', '--manifest-path', str(RASTERIZER), '--offline', '--',
        str(SVG_DIRECTORY), str(PNG_DIRECTORY), str(RASTER_INSET_PX), str(INK_SIZE_PX),
    ], check=True)


def embed(mapping):
    lines = [
        '//! Generated by tools/import_picture_shape_icons.py; LibreOffice Yaru artwork.',
        'pub(super) fn png(preset: &str) -> Option<&\'static [u8]> {',
        '    match preset {',
    ]
    for preset in mapping:
        assert (PNG_DIRECTORY / f'{preset}.png').is_file(), preset
        lines.append(f'        "{preset}" => Some(include_bytes!("../../assets/picture-crops/{preset}.png")),')
    lines.extend(['        _ => None,', '    }', '}'])
    EMBEDDED.write_text('\n'.join(lines) + '\n')


def main():
    mapping = json.loads(MAPPING.read_text())
    SVG_DIRECTORY.mkdir(parents=True, exist_ok=True)
    PNG_DIRECTORY.mkdir(parents=True, exist_ok=True)
    if len(sys.argv) > 1:
        import_sources(mapping, Path(sys.argv[1]))
    rasterize()
    embed(mapping)
    print(f'Imported {len(mapping)} LibreOffice picture-shape icons')


if __name__ == '__main__':
    main()
