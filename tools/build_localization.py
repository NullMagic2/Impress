#!/usr/bin/env python3
"""Give translatable XRC controls stable bindings and generate localization hooks.

Run after the dialog/ribbon generators. Text contents, fonts, IDs and document
values are not translated. Read-only choices keep their selection indices.
"""
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from localization_kit import name_translatable_controls

ROOT = Path(__file__).resolve().parents[1]
GUI = ROOT / 'crates/gui'
LINES = ['// Generated by tools/build_localization.py. Do not edit.',
         'use wxdragon::prelude::*;', 'use super::{Localize, text};']
RESOURCES = dict(re.findall(r'include_xrc!\("\.\./ui/([^"/]+)",\s*(\w+)\)', (GUI/'src/main.rs').read_text()))
CHOICES = set()
CHOICE_VALUES = {}
STRINGS = set()

def literal(value):
    return json.dumps(value, ensure_ascii=False)

for filename, binding in RESOURCES.items():
    path = GUI/'ui'/filename
    root = ET.parse(path).getroot()
    name_translatable_controls(root)
    LINES.append(f'impl Localize for crate::{binding} {{ fn localize(&self) {{')
    count = 0
    for obj in root.iter('object'):
        cls = obj.get('class', '')
        if not cls.startswith('wx') or cls.endswith('Sizer'): continue
        fields = [(tag, obj.findtext(tag)) for tag in ['label', 'title', 'tooltip', 'hint']]
        content = obj.find('content') if cls in ['wxComboBox','wxListBox'] else None
        if not any(value for _, value in fields) and content is None: continue
        count += 1
        name = obj.get('name')
        if not name:
            name = f'i18n_control_{count}'
            obj.set('name', name)
        for tag, value in fields:
            if not value: continue
            STRINGS.add(value)
            method = {'label':'set_label','title':'set_title' if cls == 'wxFrame' else 'set_label','tooltip':'set_tooltip','hint':'set_hint'}[tag]
            if cls in ['wxTextCtrl','wxSpinCtrl','wxSpinCtrlDouble']: continue
            LINES.append(f'self.{name}.{method}(&text({literal(value)}));')
        if content is not None:
            values = [item.text or '' for item in content.findall('item')]
            if not values: continue
            CHOICES.add(name)
            if cls == "wxComboBox": CHOICE_VALUES[name]=values
            STRINGS.update(values)
            LINES.append(f'let selected = self.{name}.get_selection();')
            if cls == 'wxComboBox': LINES.append(f'let current = self.{name}.get_value();')
            LINES.append(f'self.{name}.clear();')
            for value in values:
                LINES.append(f'self.{name}.append(&text({literal(value)}));')
            if cls == 'wxListBox': LINES.append(f'if let Some(index) = selected {{ self.{name}.set_selection(index,true); }}')
            else: LINES.append(f'if let Some(index) = selected {{ self.{name}.set_selection(index); }} else {{ self.{name}.change_value(&current); }}')
    top = root.find('object').get('name')
    LINES.append(f'self.{top}.layout();' + '} }')
    ET.indent(root, space='  ')
    if filename == 'main.xrc':
        path.write_text('<?xml version="1.0" encoding="UTF-8"?>\n'+ET.tostring(root,encoding='unicode',short_empty_elements=False)+'\n')
    else: ET.ElementTree(root).write(path, encoding='utf-8', xml_declaration=True)
LINES.append('pub(super) fn canonical_choice(name:&str,value:&str)->String { match name {')
for name,values in sorted(CHOICE_VALUES.items()):
    arguments=', '.join(literal(value) for value in values)
    LINES.append(f'{literal(name)} => super::choice_source(value,&[{arguments}]),')
LINES.append('_ => value.to_string(), } }')
(GUI/'src/i18n').mkdir(exist_ok=True)
(GUI/'src/i18n/widgets.rs').write_text('\n'.join(LINES)+'\n')
(GUI/'assets/locales/resource-strings.json').write_text(json.dumps(sorted(STRINGS),ensure_ascii=False,indent=2)+'\n')
(GUI/'assets/locales/readonly-controls.json').write_text(json.dumps(sorted(CHOICES),indent=2)+'\n')
print(f'Generated localization for {len(RESOURCES)} resources, {len(STRINGS)} strings.')
