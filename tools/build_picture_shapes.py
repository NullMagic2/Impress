"""Compile the vendored DrawingML preset data into bounded Rust tables."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/drawingml-shapes/presetShapeDefinitions.xml'
OUTPUT = ROOT / 'crates/render/src/picture_shapes/presets.rs'
NAMESPACE = '{http://schemas.openxmlformats.org/drawingml/2006/main}'

def quoted(value):
    return json.dumps(value)

def optional(value):
    return 'None' if value is None else f'Some({quoted(value)})'

def commands(path):
    result = []
    names = {'moveTo': 'Move', 'lnTo': 'Line', 'quadBezTo': 'Quad', 'cubicBezTo': 'Cubic'}
    for command in path:
        name = command.tag.removeprefix(NAMESPACE)
        if name == 'close':
            result.append('Command::Close')
        elif name == 'arcTo':
            arguments = [command.attrib[key] for key in ['wR','hR','stAng','swAng']]
            result.append('Command::Arc(' + ','.join(map(quoted, arguments)) + ')')
        else:
            arguments = [point.attrib[key] for point in command for key in ['x','y']]
            result.append('Command::' + names[name] + '(' + ','.join(map(quoted, arguments)) + ')')
    return ','.join(result)

def formula(value):
    # Eight POI 5.4.1 arrow guides contain an extra, unused trailing zero.
    parts = value.split()
    if len(parts) == 5 and parts[0] == '+-' and parts[-1] == '0':
        return ' '.join(parts[:4])
    return value


def guides(shape, name):
    return ','.join('(' + quoted(g.attrib['name']) + ',' + quoted(formula(g.attrib['fmla'])) + ')' for g in ([] if shape.find(NAMESPACE+name) is None else shape.find(NAMESPACE+name)))

lines = ['//! Generated by tools/build_picture_shapes.py from Apache POI preset data.',
         'use super::{Command, Preset, ShapePath};', 'pub(super) static PRESETS: &[Preset] = &[']
for shape in ET.parse(SOURCE).getroot():
    lines.append('Preset { name: '+quoted(shape.tag)+', adjustments: &['+guides(shape,'avLst')+'], guides: &['+guides(shape,'gdLst')+'], paths: &[')
    for path in shape.find(NAMESPACE+'pathLst'):
        lines.append('ShapePath { width: '+optional(path.get('w'))+', height: '+optional(path.get('h'))+', fill: '+str(path.get('fill')!='none').lower()+', stroke: '+str(path.get('stroke')!='false').lower()+', commands: &['+commands(path)+'] },')
    lines.append('] },')
lines.append('];')
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text('\n'.join(lines)+'\n')
print(OUTPUT)

# Shape names are product labels, kept separately from the standard geometry.
choices = json.loads((ROOT / 'design/picture-shapes.json').read_text())
choices_output = ROOT / 'crates/gui/src/ribbon/picture_shape_choices.rs'
choice_lines = ['//! Generated by tools/build_picture_shapes.py from design/picture-shapes.json.', 'use super::Choice;', 'pub(super) const CHOICES: &[Choice] = &[']
for choice in choices:
    choice_lines.append('Choice { preset: '+quoted(choice['preset'])+', label: '+quoted(choice['label'])+', group: '+quoted(choice['group'])+' },')
choice_lines.append('];')
choices_output.write_text('\n'.join(choice_lines)+'\n')
print(choices_output)
