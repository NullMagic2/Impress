#!/usr/bin/env python3
"""Refresh the Rust icon dispatch from checked-in PNGs."""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'crates/gui/assets/ribbon'
records = []
for png in sorted(OUT.glob('*.png')):
    image = Image.open(png)
    records.append(dict(name=png.stem,width=image.width,height=image.height))
for raw in OUT.glob('*.rgba'):
    raw.unlink()
(OUT / 'manifest.json').write_text(json.dumps(records,indent=2)+'\n',encoding='utf-8')
source = '// Generated by tools/embed_ribbon_pngs.py; PNGs are embedded in the Rust executable.\n'
source += "pub fn asset(name: &str) -> Option<(&'static str, &'static [u8], u32, u32)> {\n    match name {\n"
for record in records:
    name = record['name']
    source += f'        "{name}" => Some(("{name}", include_bytes!("../../assets/ribbon/{name}.png"), {record["width"]}, {record["height"]})),\n'
source += '        _ => None,\n    }\n}\n'
(ROOT / 'crates/gui/src/ribbon/embedded.rs').write_text(source,encoding='utf-8')
print(f'Embedded {len(records)} native icons')
